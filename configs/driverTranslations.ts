export function driverStatusLabel(status: string, language: SupportedLocale): string {
  const labels: Record<string, Record<"en" | "pt" | "fr" | "es", string>> = {
    draft: { en: "Draft", pt: "Rascunho", fr: "Brouillon", es: "Borrador" },
    pending_verification: { en: "Pending verification", pt: "Verificação pendente", fr: "En attente", es: "Pendiente" },
    approved: { en: "Approved", pt: "Aprovado", fr: "Approuvé", es: "Aprobado" },
    rejected: { en: "Rejected", pt: "Rejeitado", fr: "Rejeté", es: "Rechazado" },
    suspended: { en: "Suspended", pt: "Suspenso", fr: "Suspendu", es: "Suspendido" },
    expired_documents: { en: "Expired documents", pt: "Documentos expirados", fr: "Documents expirés", es: "Documentos vencidos" },
  };
  return labels[status]?.[language] ?? status;
}
