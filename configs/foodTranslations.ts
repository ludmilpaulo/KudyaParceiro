export const foodTranslations: Record<SupportedLocale, Record<FoodTranslationKey, string>> = { en, pt, fr, es };

export function foodT(
  locale: SupportedLocale | string,
  key: FoodTranslationKey,
  vars?: Record<string, string | number>,
): string {
  const bundle = foodTranslations[locale as SupportedLocale] ?? foodTranslations.en;
  const template = bundle[key] ?? foodTranslations.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
